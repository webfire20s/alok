| PAYMENT INFO
|--------------------------------------------------------------------------
*/

$pdf->Ln(10);

$pdf->SetFont('Arial', '', 10);

$pdf->Cell(
    0,
    6,
    'Payment Method: ' .
    ucfirst($order['payment_method']),
    0,
    1
