<?php

require 'includes/db.php';
require 'includes/fpdf/fpdf.php';

/*
|--------------------------------------------------------------------------
| GET ORDER
|--------------------------------------------------------------------------
*/

$orderId = (int)($_GET['order'] ?? 0);

$orderStmt = $pdo->prepare("
    SELECT *
    FROM orders
    WHERE id = ?
");

$orderStmt->execute([$orderId]);

$order = $orderStmt->fetch();

if(!$order){

    die("Order not found");

}

/*
|--------------------------------------------------------------------------
| GET ORDER ITEMS
|--------------------------------------------------------------------------
*/

$itemStmt = $pdo->prepare("
    SELECT
        order_items.*,

        closure_options.name AS closure_option_name,
        closure_options.image AS closure_option_image

    FROM order_items

    LEFT JOIN closure_options
        ON order_items.closure_option_id = closure_options.id

    WHERE order_items.order_id = ?
    ORDER BY order_items.id ASC
");

$itemStmt->execute([$orderId]);

$items = $itemStmt->fetchAll();

/*
|--------------------------------------------------------------------------
| PDF
|--------------------------------------------------------------------------
*/

$pdf = new FPDF();

$pdf->AddPage();

$pdf->SetAutoPageBreak(true, 20);

/*
|--------------------------------------------------------------------------
| LOGO
|--------------------------------------------------------------------------
*/

$logoPath =
'assets/themes/storefront/public/images/logo.jpeg';

if(file_exists($logoPath)){

    $pdf->Image($logoPath, 10, 10, 40);

}

/*
|--------------------------------------------------------------------------
| COMPANY INFO
|--------------------------------------------------------------------------
*/

$pdf->SetFont('Arial', 'B', 18);

$pdf->Cell(0, 10, 'TAX INVOICE', 0, 1, 'R');

$pdf->Ln(10);

$pdf->SetFont('Arial', '', 11);

$pdf->Cell(100, 24, 'Alok Glass Works', 0, 0);

$pdf->Cell(
    90,
    6,
    'Invoice #: ' . $order['order_number'],
    0,
    1,
    'R'
);

$pdf->Cell(
    100,
    25,
    'India',
    0,
    0
);

$pdf->Cell(
    90,
    6,
    'Date: ' .
    date(
        'd M Y',
        strtotime($order['created_at'])
    ),
    0,
    1,
    'R'
);

$pdf->Ln(10);

/*
|--------------------------------------------------------------------------
| BILLING DETAILS
|--------------------------------------------------------------------------
*/

$pdf->SetFont('Arial', 'B', 12);

$pdf->Cell(0, 8, 'Billing Details', 0, 1);

$pdf->SetFont('Arial', '', 11);

$pdf->Cell(
    0,
    6,
    $order['customer_name'],
    0,
    1
);

$pdf->Cell(
    0,
    6,
    $order['customer_email'],
    0,
    1
);

$pdf->Cell(
    0,
    6,
    $order['customer_phone'],
    0,
    1
);

if(!empty($order['customer_company'])){

    $pdf->Cell(
        0,
        6,
        $order['customer_company'],
        0,
        1
    );

}

$pdf->MultiCell(
    0,
    6,
    $order['customer_address']
);

$pdf->Cell(
    0,
    6,
    $order['customer_city'] .
    ', ' .
    $order['customer_state'] .
    ' - ' .
    $order['customer_pincode'],
    0,
    1
);

$pdf->Ln(10);

/*
|--------------------------------------------------------------------------
| TABLE HEADER
|--------------------------------------------------------------------------
*/

$pdf->SetFont('Arial', 'B', 10);

$pdf->SetFillColor(230,230,230);

$pdf->Cell(60, 10, 'Product', 1, 0, 'C', true);

$pdf->Cell(18, 10, 'Qty', 1, 0, 'C', true);

$pdf->Cell(25, 10, 'Type', 1, 0, 'C', true);

$pdf->Cell(25, 10, 'Price', 1, 0, 'C', true);

$pdf->Cell(20, 10, 'GST', 1, 0, 'C', true);

$pdf->Cell(42, 10, 'Total', 1, 1, 'C', true);

/*
|--------------------------------------------------------------------------
| TABLE ITEMS
|--------------------------------------------------------------------------
*/

/*
|--------------------------------------------------------------------------
| TABLE ITEMS
|--------------------------------------------------------------------------
*/

$pdf->SetFont('Arial', '', 10);

foreach($items as $item){

    /*
    |--------------------------------------------------------------------------
    | DETERMINE ITEM TYPE
    |--------------------------------------------------------------------------
    |
    | Normal product:
    | product_id exists
    |
    | Closure:
    | product_id is NULL
    | closure_option_id exists
    |
    */

    $isClosure =
        empty($item['product_id']) &&
        !empty($item['closure_option_id']);


    /*
    |--------------------------------------------------------------------------
    | CLOSURE ITEM
    |--------------------------------------------------------------------------
    */

    if($isClosure){

        $closureName =
            !empty($item['closure_option_name'])
                ? $item['closure_option_name']
                : 'Closure';


        $closurePrice =
            (float)$item['closure_option_price'];


        $closureQty =
            (int)$item['quantity'];


        $closureGST =
            (float)$item['gst_percent'];


        $closureTotal =
            (float)$item['line_total'];


        $productText =
            'Closure : ' . $closureName;


        $rowHeight = 10;


        /*
        |--------------------------------------------------------------------------
        | PRODUCT NAME
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            60,
            $rowHeight,
            $productText,
            1,
            0,
            'L'
        );


        /*
        |--------------------------------------------------------------------------
        | QUANTITY
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            18,
            $rowHeight,
            $closureQty,
            1,
            0,
            'C'
        );


        /*
        |--------------------------------------------------------------------------
        | TYPE
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            25,
            $rowHeight,
            'Piece',
            1,
            0,
            'C'
        );


        /*
        |--------------------------------------------------------------------------
        | PRICE
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            25,
            $rowHeight,
            'Rs. ' . number_format($closurePrice, 2),
            1,
            0,
            'R'
        );


        /*
        |--------------------------------------------------------------------------
        | GST
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            20,
            $rowHeight,
            $closureGST . '%',
            1,
            0,
            'C'
        );


        /*
        |--------------------------------------------------------------------------
        | TOTAL
        |--------------------------------------------------------------------------
        */

        $pdf->Cell(
            42,
            $rowHeight,
            'Rs. ' . number_format($closureTotal, 2),
            1,
            1,
            'R'
        );


        continue;
    }


    /*
    |--------------------------------------------------------------------------
    | NORMAL PRODUCT
    |--------------------------------------------------------------------------
    */

    $productPrice =
        (float)$item['price'];


    $quantity =
        (int)$item['quantity'];


    $gstPercent =
        (float)$item['gst_percent'];


    $lineTotal =
        (float)$item['line_total'];


    $productText =
        $item['product_name'];


    /*
    |--------------------------------------------------------------------------
    | PRODUCT ROW
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        60,
        10,
        $productText,
        1,
        0,
        'L'
    );


    /*
    |--------------------------------------------------------------------------
    | QUANTITY
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        18,
        10,
        $quantity,
        1,
        0,
        'C'
    );


    /*
    |--------------------------------------------------------------------------
    | ORDER UNIT
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        25,
        10,
        ucfirst($item['order_unit']),
        1,
        0,
        'C'
    );


    /*
    |--------------------------------------------------------------------------
    | PRODUCT PRICE
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        25,
        10,
        'Rs. ' . number_format($productPrice, 2),
        1,
        0,
        'R'
    );


    /*
    |--------------------------------------------------------------------------
    | GST
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        20,
        10,
        $gstPercent . '%',
        1,
        0,
        'C'
    );


    /*
    |--------------------------------------------------------------------------
    | PRODUCT TOTAL
    |--------------------------------------------------------------------------
    */

    $pdf->Cell(
        42,
        10,
        'Rs. ' . number_format($lineTotal, 2),
        1,
        1,
        'R'
    );

}
/*
/*
