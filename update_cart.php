<?php

session_start();

require 'includes/db.php';

/*
|--------------------------------------------------------------------------
| GET DATA
|--------------------------------------------------------------------------
*/

$id = (int)($_POST['id'] ?? 0);

$quantity = (int)($_POST['quantity'] ?? 1);

/*
|--------------------------------------------------------------------------
| VALIDATION
|--------------------------------------------------------------------------
*/

if($quantity < 1){

    $quantity = 1;

}

/*
|--------------------------------------------------------------------------
| UPDATE CART
|--------------------------------------------------------------------------
*/

$stmt = $pdo->prepare("
    UPDATE cart
    SET quantity = ?
    WHERE id = ?
");

$stmt->execute([
    $quantity,
    $id
]);

/*
|--------------------------------------------------------------------------
| REDIRECT
|--------------------------------------------------------------------------
*/

header("Location: cart.php");

exit;